def _password() -> str:
	path = os.environ.get("NORIA_DEMO_PASSWORD_FILE")
	if path and os.path.exists(path):
		with open(path) as fh:
			return fh.read().strip()
	raise RuntimeError("NORIA_DEMO_PASSWORD_FILE is required (run noria.sh init-secrets)")


def _as(user: str):
	frappe.set_user(user)


def _call(client, op, **args):
	result = ledger_api.call(client, op, args)
	frappe.db.commit()  # keep hub transactions short (see utils.touch_client)
	return result


def run():
	if frappe.conf.get("noria_environment") == "production" or os.environ.get("NORIA_ENV") == "production":
		raise RuntimeError("Refusing to seed demo data in production")
	password = _password()
	firm_ids = {}
	for f in FIRMS:
		admin_email, admin_name = f["admin"]
		existing = frappe.db.get_value("Accounting Firm", {"firm_name": f["firm_name"]}, "name")
		if existing:
			firm_ids[f["key"]] = existing
			continue
		frappe.set_user("Administrator")
		result = create_firm_with_admin(f["firm_name"], f["firm_type"], admin_name, admin_email, password=password, modules=ALL_MODULES)
		firm_ids[f["key"]] = result["firm"]
		_as(admin_email)
		for email, name, role in f["members"]:
			firm_api.add_member(result["firm"], email, name, role, password=password)
		frappe.db.commit()
		print(f"firm {f['firm_name']} -> {result['firm']}")

	for c in CLIENTS:
		firm = firm_ids[c["firm"]]
		admin = next(x["admin"][0] for x in FIRMS if x["key"] == c["firm"])
		_as(admin)
		client = frappe.db.get_value("Client Business", {"business_name": c["business_name"]}, "name")
		if not client:
			client = clients_api.create(
				firm=firm,
				business_name=c["business_name"],
				kra_pin=c["kra_pin"],
				industry=c["industry"],
				vat_registered=c["vat_registered"],
				fiscal_year_start=c["fiscal_year_start"],
				chart_of_accounts=c["chart_of_accounts"],
				services=list(ALL_MODULES),
				monthly_retainer=c["retainer"],
				provision=False,
			)["name"]
			frappe.db.commit()
		if frappe.db.get_value("Client Business", client, "provisioning_status") != "Ready":
			print(f"provisioning {c['business_name']} ({client}) ...")
			frappe.set_user("Administrator")
			provision_client_site(client)
			frappe.db.commit()
		_as(admin)
		for user, role in c["team"]:
			clients_api.assign(client, user, role)
		if c["portal"]:
			clients_api.invite_portal_user(client, c["portal"][0], c["portal"][1], "Owner", True, password=password)
		frappe.db.commit()

		if not frappe.db.exists("Practice Task", {"client": client}):
			worker = c["team"][0][0] if c["team"] else admin
			_as(worker)
			seed_books(client, c)
			frappe.db.commit()

	for key, firm in firm_ids.items():
		frappe.set_user("Administrator")
		generate_for_firm(firm, "2026-09")
		frappe.db.commit()

	seed_practice_flow(firm_ids)
	frappe.set_user("Administrator")
	for client in frappe.get_all("Client Site", filters={"status": "Active"}, pluck="client"):
		ledger_api.refresh_client_stats(client)
	frappe.db.commit()
	print("demo data ready")


def _accounts(client):
	accts = _call(client, "postable_accounts")
	by_type = {}
	for a in accts:
		by_type.setdefault((a["root_type"], a["account_type"] or ""), []).append(a["name"])

	def find(root, contains=None, account_type=""):
		for a in accts:
			if a["root_type"] == root and (not account_type or a["account_type"] == account_type):
				if not contains or contains.lower() in a["account_name"].lower():
					return a["name"]
		raise RuntimeError(f"No {root}/{contains}/{account_type} account in {client}")

	return find


def seed_books(client: str, c: dict):
	find = _accounts(client)
	cash = find("Asset", "Cash", "Cash")
	sales = find("Income", "Sales")
	service = find("Income", "Service")
	admin_exp = find("Expense", "Administrative")
	office_exp = find("Expense", "Office")
	equity = find("Equity", "Capital")

	bank_name, acct_name, acct_no = c["bank"]
	banks = {b["bank"]: b for b in _call(client, "bank_accounts")}
	if bank_name in banks:
		bank_account, bank_gl = banks[bank_name]["name"], banks[bank_name]["account"]
	else:
		bank = _call(client, "create_bank_account", bank_name=bank_name, account_name=acct_name, account_number=acct_no,
		             idempotency_key=f"seed-{client}-bank")
		bank_gl, bank_account = bank["gl_account"], bank["name"]

	# Opening capital
	_call(client, "create_journal", posting_date="2026-09-01", user_remark="Opening capital introduced",
	      lines=[{"account": bank_gl, "debit": "500000.00"}, {"account": equity, "credit": "500000.00"}],
	      submit=True, idempotency_key=f"seed-{client}-open")

	customers = ["Nairobi Java House Supplies", "Uptown Cafe Ltd", "Westlands Deli"]
	suppliers = ["Highland Beans Cooperative", "Packaging Kenya Ltd", "Kenya Power"]
	for party_type, names in (("Customer", customers), ("Supplier", suppliers)):
		existing = {p["name"] for p in _call(client, "parties", party_type=party_type)}
		for name in names:
			if name not in existing:
				_call(client, "create_party", party_type=party_type, party_name=name)

	tax = None
	if c["vat_registered"]:
		templates = _call(client, "tax_templates", kind="sales")
		tax = templates[0]["name"] if templates else None

	invoices = []
	for i, (cust, amount, day) in enumerate([(customers[0], "120000.00", 5), (customers[1], "85000.00", 12), (customers[2], "42000.00", 20)]):
		inv = _call(client, "create_invoice", kind="sales", party=cust, posting_date=f"2026-09-{day:02d}",
		            due_date=f"2026-10-{day:02d}", taxes_and_charges=tax,
		            items=[{"item_name": "Roasted coffee (kg)" if i != 2 else "Barista training", "qty": 1, "rate": amount,
		                    "account": sales if i != 2 else service}],
		            submit=True, idempotency_key=f"seed-{client}-si-{i}")
		invoices.append(inv)

	bills = []
	for i, (sup, amount, day, acc) in enumerate([(suppliers[0], "60000.00", 3, office_exp), (suppliers[1], "18500.00", 9, admin_exp),
	                                             (suppliers[2], "7400.00", 25, admin_exp)]):
		bill = _call(client, "create_invoice", kind="purchase", party=sup, posting_date=f"2026-09-{day:02d}",
		             due_date=f"2026-09-{min(day + 14, 30):02d}", bill_no=f"B-{1000 + i}",
		             items=[{"item_name": f"Supply {i + 1}", "qty": 1, "rate": amount, "account": acc}],
		             submit=True, idempotency_key=f"seed-{client}-pi-{i}")
		bills.append(bill)

	# Receipts and payments through the bank
	r1 = _call(client, "pay_invoice", kind="sales", invoice=invoices[0]["name"], account=bank_gl, posting_date="2026-09-18",
	           reference_no="EFT-SEED-001", reference_date="2026-09-18", idempotency_key=f"seed-{client}-rcpt-0")
	_call(client, "pay_invoice", kind="sales", invoice=invoices[1]["name"], account=bank_gl, posting_date="2026-09-26",
	      amount="50000.00", reference_no="EFT-SEED-002", reference_date="2026-09-26", idempotency_key=f"seed-{client}-rcpt-1")
	p1 = _call(client, "pay_invoice", kind="purchase", invoice=bills[0]["name"], account=bank_gl, posting_date="2026-09-15",
	           reference_no="CHQ-5501", reference_date="2026-09-15", idempotency_key=f"seed-{client}-pay-0")
	# Petty cash expense
	_call(client, "record_simple", kind="expense", posting_date="2026-09-10", amount="2500.00", cash_account=cash,
	      category_account=admin_exp, description="Office tea and sugar", idempotency_key=f"seed-{client}-petty-0")

	# Bank statement for September (CSV) and reconciliation of the matching lines
	grand0 = invoices[0]["grand_total"]
	csv_text = "\n".join(
		[
			"Date,Description,Reference,Money In,Money Out",
			"01/09/2026,Capital injection,CAP-1,500000.00,",
			f"15/09/2026,Cheque 5501 Highland Beans,CHQ-5501,,{bills[0]['grand_total']:.2f}",
			f"18/09/2026,EFT {customers[0]},EFT-SEED-001,{grand0:.2f},",
			"26/09/2026,EFT Uptown Cafe,EFT-SEED-002,50000.00,",
			"30/09/2026,Monthly ledger fee,,,450.00",
		]
	)
	imp = _call(client, "import_statement", bank_account=bank_account, format="generic_csv", content=csv_text,
	            idempotency_key=f"seed-{client}-stmt-sep")
	lines = _call(client, "bank_transactions", bank_account=bank_account, status="Unreconciled")
	for line in lines:
		if line["reference_number"] == "EFT-SEED-001":
			_call(client, "reconcile", bank_transaction=line["name"],
			      vouchers=[{"payment_doctype": "Payment Entry", "payment_name": r1["name"], "amount": grand0}])
		elif line["reference_number"] == "CHQ-5501":
			_call(client, "reconcile", bank_transaction=line["name"],
			      vouchers=[{"payment_doctype": "Payment Entry", "payment_name": p1["name"], "amount": bills[0]["grand_total"]}])
		elif "ledger fee" in (line["description"] or "").lower():
			_call(client, "categorize", bank_transaction=line["name"], account=admin_exp, remark="Bank charges")
	# Leave capital injection + Uptown receipt unreconciled as live examples.
	print(f"  {client}: imported {imp['created']} bank lines")

	if c["mpesa"] and "Safaricom M-PESA" not in banks:
		mpesa_bank = _call(client, "create_bank_account", bank_name="Safaricom M-PESA", account_name="Till 123456",
		                   account_number="123456", idempotency_key=f"seed-{client}-mpesa")
		mpesa_csv = "\n".join(
			[
				"Receipt No.,Completion Time,Details,Transaction Status,Paid In,Withdrawn,Balance",
				"SIA1B2C3D4,2026-09-21 10:15:00,Customer Payment to Small Business,Completed,1500.00,,1500.00",
				"SIB2C3D4E5,2026-09-22 14:02:11,Customer Payment to Small Business,Completed,2350.00,,3850.00",
				"SIC3D4E5F6,2026-09-23 09:40:00,Pay Bill to 888880 - KPLC,Completed,,-1200.00,2650.00",
				"SID4E5F6G7,2026-09-23 18:00:00,Customer Payment to Small Business,Failed,900.00,,2650.00",
			]
		)
		_call(client, "import_statement", bank_account=mpesa_bank["name"], format="mpesa_csv", content=mpesa_csv,
		      idempotency_key=f"seed-{client}-mpesa-sep")


